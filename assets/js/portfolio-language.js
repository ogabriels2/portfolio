/* Native language links remain usable without this optional drag enhancement. */
(function () {
  'use strict';

  function init() {
    document.querySelectorAll('.lang-switcher-container').forEach(function (container) {
      if (container.dataset.languageEnhanced) return;
      var links = Array.from(container.querySelectorAll('a.lang-item[href]'));
      var pill = container.querySelector('.gliding-pill');
      if (links.length !== 2 || !pill) return;
      container.dataset.languageEnhanced = 'true';

      var reduced = window.matchMedia('(prefers-reduced-motion: reduce)');
      var gesture = null;
      var suppressClick = null;
      function language(link) {
        return (link.dataset.lang || link.getAttribute('lang') || '').split('-')[0];
      }
      function currentIndex() {
        var index = links.findIndex(function (link) {
          return language(link) === container.dataset.active;
        });
        return index < 0 ? Math.max(0, links.findIndex(function (link) {
          return link.classList.contains('active');
        })) : index;
      }
      function modified(event) {
        return event.ctrlKey || event.metaKey || event.shiftKey || event.altKey;
      }
      function position(event) {
        return Math.max(0, Math.min(gesture.travel,
          gesture.start + event.clientX - gesture.x));
      }
      function clean() {
        var previous = gesture;
        gesture = null;
        window.removeEventListener('pointermove', move);
        window.removeEventListener('pointerup', end);
        window.removeEventListener('pointercancel', cancel);
        window.removeEventListener('blur', cancel);
        window.removeEventListener('resize', cancel);
        window.removeEventListener('keydown', escape);
        document.removeEventListener('visibilitychange', visibility);
        container.classList.remove('is-dragging');
        pill.style.removeProperty('transform');
        if (previous && container.hasPointerCapture(previous.id)) {
          container.releasePointerCapture(previous.id);
        }
        return previous;
      }
      function cancel(event) {
        if (!gesture || (event && 'pointerId' in event && event.pointerId !== gesture.id)) return;
        var previous = clean();
        if (previous.dragging) suppressClick = previous.id;
      }
      function escape(event) {
        if (event.key === 'Escape') cancel();
      }
      function visibility() {
        if (document.hidden) cancel();
      }
      function move(event) {
        if (!gesture || event.pointerId !== gesture.id) return;
        var dx = event.clientX - gesture.x;
        var dy = event.clientY - gesture.y;
        if (!gesture.dragging) {
          if (Math.abs(dy) > 6 && Math.abs(dy) >= Math.abs(dx)) {
            cancel();
            return;
          }
          if (Math.abs(dx) <= 6 || Math.abs(dx) <= Math.abs(dy) * 1.25) return;
          gesture.dragging = true;
          container.classList.add('is-dragging');
          try {
            container.setPointerCapture(event.pointerId);
          } catch (error) {
            cancel();
            return;
          }
        }
        if (event.cancelable) event.preventDefault();
        var bounded = position(event);
        var over = gesture.start + dx - bounded;
        var elastic = reduced.matches ? 0 : Math.max(-6, Math.min(6, over * 0.14));
        var stretch = reduced.matches ? 0 : Math.min(0.06, Math.abs(dx) / 900);
        pill.style.transform = 'translateX(' + (bounded + elastic) + 'px) scale(' +
          (1.05 + stretch) + ',' + (1.05 - stretch * 0.5) + ')';
      }
      function end(event) {
        if (!gesture || event.pointerId !== gesture.id) return;
        var target = position(event) > gesture.travel / 2 ? 1 : 0;
        var previous = clean();
        if (!previous.dragging) return;
        suppressClick = previous.id;
        if (target !== previous.index) {
          /* Preserve the page's language state until its native counterpart loads. */
          window.location.assign(links[target].href);
        }
      }

      container.addEventListener('pointerdown', function (event) {
        /* A new physical press cannot be the click generated by an earlier drag. */
        suppressClick = null;
        if (gesture || !event.isPrimary || event.button !== 0 || modified(event)) return;
        var travel = pill.offsetWidth;
        if (!travel) return;
        var index = currentIndex();
        gesture = {
          id: event.pointerId, x: event.clientX, y: event.clientY,
          index: index, start: index * travel, travel: travel, dragging: false
        };
        window.addEventListener('pointermove', move, { passive: false });
        window.addEventListener('pointerup', end);
        window.addEventListener('pointercancel', cancel);
        window.addEventListener('blur', cancel);
        window.addEventListener('resize', cancel);
        window.addEventListener('keydown', escape);
        document.addEventListener('visibilitychange', visibility);
      });
      container.addEventListener('lostpointercapture', function (event) {
        if (gesture && event.pointerId === gesture.id) cancel();
      });
      container.addEventListener('dragstart', function (event) {
        if (gesture) event.preventDefault();
      });
      container.addEventListener('click', function (event) {
        if (suppressClick === null || event.detail === 0 || modified(event)) return;
        if ('pointerId' in event && event.pointerId !== suppressClick) return;
        suppressClick = null;
        event.preventDefault();
        event.stopImmediatePropagation();
      }, true);
    });
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init, { once: true });
  } else {
    init();
  }
}());
